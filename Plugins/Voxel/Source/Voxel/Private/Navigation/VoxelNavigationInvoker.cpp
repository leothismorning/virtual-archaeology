void FVoxelNavigationInvokerManager::LogInvokers()
{
	VOXEL_FUNCTION_COUNTER();
	checkVoxelSlow(IsInGameThread());

	const UWorld* World = GetWorld().Resolve();
	if (!ensure(World))
	{
		return;
	}

	LOG_VOXEL(Log, "Navigation invokers for %s:", *World->GetPathName());

	for (const UVoxelNavigationInvokerComponent* Invoker : InvokerComponents)
	{
		LOG_VOXEL(Log, "\tEnabled: %s Radius: %f %s", *LexToString(Invoker->bEnabled), Invoker->Radius, *Invoker->GetPathName());
	}
}

TSharedRef<FVoxelNavigationInvokerView> FVoxelNavigationInvokerManager::MakeView(
	const int32 ChunkSize,
	const FTransform& LocalToWorld)
{
	VOXEL_FUNCTION_COUNTER();
	check(IsInGameThread());

	const TSharedRef<FVoxelNavigationInvokerView> View = MakeShared<FVoxelNavigationInvokerView>(
		ChunkSize,
		LocalToWorld);

	// Ensure the view is up to date in the first query
	{
		FVoxelTaskScope Scope(*GVoxelGlobalTaskContext);
		View->Tick(InvokerComponents);
	}

	WeakViews.Add(View);
	return View;
}

///////////////////////////////////////////////////////////////////////////////
///////////////////////////////////////////////////////////////////////////////
///////////////////////////////////////////////////////////////////////////////

void FVoxelNavigationInvokerManager::Tick()
{
	VOXEL_FUNCTION_COUNTER();
	check(IsInGameThread());

	const double Time = FPlatformTime::Seconds();
	if (Time < LastTickTime + 0.05)
	{
		return;
	}
	LastTickTime = Time;

	for (auto It = WeakViews.CreateIterator(); It; ++It)
	{
		const TSharedPtr<FVoxelNavigationInvokerView> View = It->Pin();
		if (!View)
		{
			It.RemoveCurrent();
			continue;
		}

		View->Tick(InvokerComponents);
	}
}

void FVoxelNavigationInvokerManager::AddReferencedObjects(FReferenceCollector& Collector)
{
	VOXEL_FUNCTION_COUNTER();

	for (auto It = InvokerComponents.CreateIterator(); It; ++It)
	{
		TObjectPtr<UVoxelNavigationInvokerComponent> InvokerComponent = *It;
		Collector.AddReferencedObject(InvokerComponent);

		if (!ensure(InvokerComponent))
		{
			It.RemoveCurrent();
		}
	}
}

